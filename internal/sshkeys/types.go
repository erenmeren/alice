package sshkeys

import (
	"time"

	"github.com/google/uuid"

	"alice/internal/secrets"
)

// Job types and periodic tasks of the module (C1). jobs registers them with their license class.
const (
	JobDeploy           = "sshkey.add"
	JobRotationLocation = "rotation.location"
	TaskPlan            = "rotation.plan"
	TaskSweep           = "rotation.sweep"
	TaskDestroyRetired  = "sshkey.destroy_retired"
)

// Constants of C1.
const (
	// RetiredKeyRetention: a retired key's private key is destroyed this long after its retirement,
	// unless the key is live somewhere again (S5).
	RetiredKeyRetention = 30 * 24 * time.Hour
	// MaxGenerations bounds the keys generated at once in the process (ErrGenerateBusy beyond).
	MaxGenerations = 2
	// PreviewMailEvery bounds on-demand preview emails: at most one per policy in this time (row 16).
	PreviewMailEvery = 10 * time.Minute
	// NoticeGrace: a scheduled run whose rotation.preview was not delivered to any Administrator by
	// this long after its planned start is cancelled (S1).
	NoticeGrace = 24 * time.Hour
)

// Result codes of runs (rotations.result_code; Task 13 maps them to ALC codes).
const (
	ReasonPolicyOff         = "rotation.policy_off"
	ReasonPlanChanged       = "rotation.plan_changed"
	ReasonCancelledLicense  = "rotation.cancelled_license"
	ReasonNoticeUndelivered = "rotation.notice_undelivered" // S1, new code ALC-ROT-0017
)

// Triggers of a run (rotations.trigger).
const (
	TriggerScheduled = "scheduled"
	TriggerManual    = "manual"
)

// Reasons of the audited refusals (details key reason of sshkey.deploy.denied and
// sshkey.private_key_download.denied).
const (
	DenyConnectionAccount = "connection_account"
	// DenyConnectionFilesUnknown: the last scan has no complete key-file list for the connection
	// account on that server (S7 fails closed); the error is ErrConnectionAccount.
	DenyConnectionFilesUnknown = "connection_account_files_unknown"
	DenyKeysManagedElsewhere   = "keys_managed_elsewhere"
	DenySSHDUnreadable         = "sshd_unreadable"
	DenyOwnKey                 = "own_key"
	DenyNotManaged             = "not_managed"
	DenyDestroyed              = "destroyed"
	DenyRetired                = "retired" // rotation.policy.denied
)

// GenerateInput asks for a new key.
type GenerateInput struct {
	Label   string // 1-100 runes, no control, format or bidi characters
	KeyType string // keymat type; "" = ed25519
}

// ManagedKey is a key Alice generated, with its private key's public facts. It never carries the
// private key.
type ManagedKey struct {
	ID, PrivateKeyID       uuid.UUID
	Fingerprint, PublicKey string
	KeyType                string // keymat type
	Bits                   int
	Label, Comment         string
	CreatedBy              uuid.UUID // uuid.Nil: generated by Alice itself (a rotation)
	CreatedAt              time.Time
	RetiredAt, DestroyedAt *time.Time
	RotatedFrom            *uuid.UUID
	DownloadCount          int
	LastDownloadedAt       *time.Time
	PolicyID               *uuid.UUID // the live rotation policy of the key
	OpenRotationID         *uuid.UUID // the unfinished rotation that replaces this key
}

// DeployInput asks for one key line on one server, user and file.
type DeployInput struct {
	KeyID, TargetID  uuid.UUID
	OSUser, FilePath string
	From             string // "" or a comma list for keymat.FromOption
	Restrict         bool
}

// DeployJob is a validated sshkey.add payload, read again from the database when the job runs.
type DeployJob struct {
	KeyID, TargetID  uuid.UUID
	Fingerprint      string
	OSUser, FilePath string
	Options, Comment string
	Line             string
	Protected        []string // ProtectedFingerprints at the time the job runs
}

// DeployOutcome is what the sshkey.add handler reports (C9's decision table).
type DeployOutcome struct {
	Result string // DeployVerified | DeployUnverified | DeployAlreadyPresent | DeployUndone | DeployFailed | DeployUndoFailed
	Reason string // closed reason for the last three
	LineNo int
	Backup string
	Note   string // verify note for DeployUnverified: "from_option", "login_without_key", "root_login_disabled"
}

// Deploy results.
const (
	DeployVerified       = "verified"
	DeployUnverified     = "unverified"
	DeployAlreadyPresent = "already_present"
	DeployUndone         = "undone"
	DeployFailed         = "failed"
	DeployUndoFailed     = "undo_failed"
)

// DownloadInput asks for a key's private key.
type DownloadInput struct {
	KeyID  uuid.UUID
	Reason string
	// Passphrase encrypts the file (nil = unencrypted). DownloadPrivateKey clears it before it
	// returns, on every path; the caller zeroes its own copies.
	Passphrase []byte
}

// Download is the OpenSSH private-key file.
type Download struct {
	FileName string            // "alice-<slug>-<first 8 hex of SHA-256(fingerprint)>.key", [a-z0-9._-] only
	Body     secrets.Plaintext // the OpenSSH file; the caller zeroes it after writing
}
