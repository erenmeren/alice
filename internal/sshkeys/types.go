// Constants of C1.
const (
	// RetiredKeyRetention: a retired key's private key is destroyed this long after its retirement,
	// unless the key is live somewhere again (S5).
	RetiredKeyRetention = 30 * 24 * time.Hour
	// MaxGenerations bounds the keys generated at once in the process (ErrGenerateBusy beyond).
	MaxGenerations = 2
	// PreviewMailEvery bounds on-demand preview emails: at most one per policy in this time (row 16).
	PreviewMailEvery = 10 * time.Minute
	// DecisionWindow is how long a run waits for an Administrator's decision on locations Alice
	// cannot test (plan.DecisionDue).
	DecisionWindow = 14 * 24 * time.Hour
	// ReverifyFreshness bounds the age of the re-check a removal relies on (plan.Fresh; the database
	// CHECK too).
	ReverifyFreshness = 15 * time.Minute
	// MaxLocationJobs bounds the sweep's re-queues of a location's job per phase.
	MaxLocationJobs = 5
	// ManualStartGrace: a manual run still previewed this long after its creation was left by a crash
	// between its insert and its start; the sweep cancels it (rotation.start_failed), never starts it.
	ManualStartGrace = 5 * time.Minute
	// maxPlanActions and maxPlanBytes are what the database stores of a plan (rotation_locations.n,
	// rotations.plan): insertRun refuses a larger plan with ErrPlanTooLarge first.
	maxPlanActions = 10000
	maxPlanBytes   = 2 << 20
)

