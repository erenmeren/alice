// managedKeyDTO is what Alice knows about a key it generated (C13). It never carries the private key, a passphrase or
// anything derived from them (S-08): only the facts of the sealed key.
type managedKeyDTO struct {
	Label            string     `json:"label"`
	Comment          string     `json:"comment"`
	KeyType          string     `json:"key_type"`
	CreatedBy        *string    `json:"created_by"` // null: generated by Alice itself (a rotation)
	CreatedAt        time.Time  `json:"created_at"`
	RetiredAt        *time.Time `json:"retired_at"`
	DestroyedAt      *time.Time `json:"destroyed_at"`
	RotatedFrom      *string    `json:"rotated_from"` // the id of the key this one replaced
	DownloadCount    int        `json:"download_count"`
	LastDownloadedAt *time.Time `json:"last_downloaded_at"`
	PolicyID         *string    `json:"policy_id"`
	OpenRotationID   *string    `json:"open_rotation_id"`
}

func managedKeyJSON(m sshkeys.ManagedKey) *managedKeyDTO {
	var by *string
	if m.CreatedBy != uuid.Nil {
		v := m.CreatedBy.String()
		by = &v
	}
	return &managedKeyDTO{
		Label: m.Label, Comment: m.Comment, KeyType: m.KeyType, CreatedBy: by, CreatedAt: m.CreatedAt.UTC(),
		RetiredAt: utcPtr(m.RetiredAt), DestroyedAt: utcPtr(m.DestroyedAt), RotatedFrom: idPtr(m.RotatedFrom),
		DownloadCount: m.DownloadCount, LastDownloadedAt: utcPtr(m.LastDownloadedAt), PolicyID: idPtr(m.PolicyID),
		OpenRotationID: idPtr(m.OpenRotationID),
	}
}

// sshKeyDetailDTO is GET /ssh-keys/{id}: the inventory's key plus managed_key (null for a key Alice found on a server
// and for Alice's own connection key).
type sshKeyDetailDTO struct {
	sshKeyDTO
	ManagedKey *managedKeyDTO `json:"managed_key"`
}

// generatedKeyJSON is the answer of a generation: the key as the detail route shows it, without locations yet.
func generatedKeyJSON(m sshkeys.ManagedKey, refs serviceRefs) sshKeyDetailDTO {
	sshType, _, _ := strings.Cut(m.PublicKey, " ")
	return sshKeyDetailDTO{
		sshKeyDTO: sshKeyDTO{
			ID: m.ID.String(), Fingerprint: m.Fingerprint, KeyType: sshType, Bits: m.Bits, PublicKey: m.PublicKey, Managed: true,
			Comment: m.Comment, FirstSeenAt: m.CreatedAt.UTC(), Service: refs.of(m.ServiceID),
		},
		ManagedKey: managedKeyJSON(m),
	}
}

type userKeyFilesDTO struct {
	OSUser      string   `json:"os_user"`
	Files       []string `json:"files"`
	DefaultFile string   `json:"default_file"`
}

type keyFilesDTO struct {
	Items     []userKeyFilesDTO `json:"items"`
	ScannedAt *time.Time        `json:"scanned_at"`
	// Refusal names why nothing can be offered on this server (null when the list is usable).
	Refusal *errorRefDTO `json:"refusal"`
}

// connectionUser is the account Alice signs in with on t (inventory.ServiceUser when the record has none).
func connectionUser(t inventory.Target) string {
	if t.Username == "" {
		return inventory.ServiceUser
	}
	return t.Username
}

// keyFilesJSON offers the users and files a key can be deployed to (C13, S7): never the connection account, never a
// file the connection account reads, and nothing at all unless the scan listed the connection account's files
// completely and exactly once (the service's own rule; it refuses a deploy otherwise). The default file is a user's
// first file. Users and paths come from the server: they are data, rendered as text.
func keyFilesJSON(t inventory.Target) keyFilesDTO {
	out := keyFilesDTO{Items: []userKeyFilesDTO{}, ScannedAt: utcPtr(t.LastDiscoveryAt)}
	conn := connectionUser(t)
	var own []string
	seen, complete := 0, false
	for _, u := range t.Facts.KeyFiles {
		if u.OSUser == conn {
			seen++
			complete = u.Complete
			own = append(own, u.Files...)
		}
	}
	if seen != 1 || !complete {
		out.Refusal = errorRef(sshkeys.ReasonConnectionFilesUnknown, nil)
		return out
	}
	for _, u := range t.Facts.KeyFiles {
		if u.OSUser == conn {
			continue
		}
		var files []string
		for _, f := range u.Files {
			if !slices.Contains(own, f) {
				files = append(files, f)
			}
		}
		if len(files) == 0 {
			continue
		}
		out.Items = append(out.Items, userKeyFilesDTO{OSUser: u.OSUser, Files: files, DefaultFile: files[0]})
	}
	return out
}
