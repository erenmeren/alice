// rolledBack checks a rollback outcome, and that the files and the served certificate are the
// previous ones again.
func (h *rnHost) rolledBack(out providers.DeployOutcome, err error, reason, failedStep, cert string, same func()) {
	t := h.t
	t.Helper()
	require.NoError(t, err)
	require.Equal(t, providers.DeployRolledBack, out.Result, "%+v", out)
	assert.Equal(t, providers.PhaseRestored, out.Phase)
	assert.Equal(t, reason, out.Reason, "%+v", out)
	assert.Equal(t, failedStep, out.FailedStep)
	same()
	h.servesRecorded(cert, 443)
}

