// committed checks a committed and verified outcome, the files and the served leaf, and records
// the new pair.
func (h *rnHost) committed(out providers.DeployOutcome, err error, req providers.DeployRequest, l pki.Leaf, mode string) {
	t := h.t
	t.Helper()
	require.NoError(t, err)
	require.Equal(t, providers.DeployCommitted, out.Result, "%+v", out)
	assert.Equal(t, providers.PhaseCommitted, out.Phase)
	assert.Equal(t, mode, out.Verified)
	assert.Empty(t, out.Reason)
	h.pair(req.Location.CertPath, req.Location.KeyPath, l)
	h.leaves[req.Location.CertPath] = l
}

// unchangedFiles is the hash of a pair's files, to compare before and after.
func (h *rnHost) unchangedFiles(cert string) func() {
	key := h.keyOf(cert)
	c, k := h.fileSHA(cert), h.fileSHA(key)
	return func() {
		h.t.Helper()
		assert.Equal(h.t, c, h.fileSHA(cert), "%s unchanged", cert)
		assert.Equal(h.t, k, h.fileSHA(key), "%s unchanged", key)
	}
}

// servesOld checks that the pair on disk is the recorded one and that the website serves it.
func (h *rnHost) servesRecorded(cert string, port int) {
	h.t.Helper()
	l := h.leaves[cert]
	h.pair(cert, h.keyOf(cert), l)
	h.settledServed(h.ip, port, l.Cert.DNSNames[0], "", pki.Fingerprint(l.Cert), cert)
}

// testDeployVerified: an ECDSA pair with its chain; the real nginx serves it (Alice's probe and an
// independent verified TLS connection); the key's 0644 becomes 0600 (F-13); a second call of the
// same operation answers committed without reloading; other websites are untouched.
func (h *rnHost) testDeployVerified(t *testing.T) {
	apiSame := h.unchangedFiles(rnAPI)
	c := h.location(rnWWW)
	l := h.leaf("www.example.test", pki.ECDSA256)
	req := h.request(c, l, true)
	out, log, err := h.deploy(nil, req)
	h.committed(out, err, req, l, "remote")
	assert.Equal(t, []string{"backup:ok", "write_key:ok", "write_cert:ok", "config_test:ok", "reload:ok", "verify:started", "verify:ok"}, log)
	h.settledServed(h.ip, 443, "www.example.test", "", pki.Fingerprint(l.Cert), "the new leaf")
	assert.Equal(t, pki.Fingerprint(l.Cert), h.dialVerified(443, "www.example.test"), "the chain verifies against the test CA")
	assert.Equal(t, "root:root 600", h.stat(rnWWWKey), "F-13: an open key mode becomes 0600")
	assert.Equal(t, "root:root 644", h.stat(rnWWW))
	apiSame()
	h.servesRecorded(rnAPI, 443)

	// The same operation again: the helper answers from its journal (the same steps, replayed), and
	// nothing is written or reloaded (the same nginx workers serve).
	workers := h.workers()
	key, cert := h.fileSHA(rnWWWKey), h.fileSHA(rnWWW)
	req.PrivateKeyPEM = secretsOf(l)
	again, log2, err := h.deploy(nil, req)
	h.committed(again, err, req, l, "remote")
	assert.Equal(t, log, log2)
	assert.Equal(t, workers, h.workers(), "no reload")
	assert.Equal(t, key, h.fileSHA(rnWWWKey))
	assert.Equal(t, cert, h.fileSHA(rnWWW))
}

