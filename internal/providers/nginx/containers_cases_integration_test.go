// testDiscovery: the test websites on the distribution's layout, through the provider: supported
// locations with their files, fingerprints, modes and servers; every unsupported case a real host
// produces, with its reason; the server-level warnings.
func (h *rnHost) testDiscovery(t *testing.T) {
	res, locs := h.discover(true)
	require.NotNil(t, res.Nginx)
	require.True(t, res.Nginx.ConfigValid, "%+v %v", *res.Nginx, res.Warnings)
	supported := func(cert string) providers.DiscoveredCertificate {
		t.Helper()
		c, ok := locs[cert]
		require.True(t, ok, "%s is listed", cert)
		assert.True(t, c.Location.Supported, "%s is supported: %+v", cert, c.Location)
		assert.Equal(t, h.keyOf(cert), c.Location.KeyPath, cert)
		assert.True(t, c.Location.KeyExists, cert)
		l := h.leaves[cert]
		first, ok := leafFingerprint(c.PEMChain)
		require.True(t, ok, cert)
		assert.Equal(t, pki.Fingerprint(l.Cert), first, "%s: the leaf on disk", cert)
		assert.Equal(t, h.fileSHA(cert), c.FileSHA256, "%s: the file's hash", cert)
		return c
	}
	unsupported := func(cert, reason string) providers.DiscoveredCertificate {
		t.Helper()
		c, ok := locs[cert]
		require.True(t, ok, "%s is listed", cert)
		assert.False(t, c.Location.Supported, cert)
		assert.Equal(t, reason, c.Location.Unsupported, "%s: %+v", cert, c.Location)
		return c
	}
	listens := func(c providers.DiscoveredCertificate) []string {
		var out []string
		for _, s := range c.Location.Servers {
			for _, l := range s.Listens {
				out = append(out, l.Addr+"|"+strconv.Itoa(l.Port))
			}
		}
		return out
	}

	www := supported(rnWWW)
	assert.Equal(t, h.leaves[rnWWW].FullchainPEM, www.PEMChain, "the chain as it is on disk")
	assert.Equal(t, "0644", www.Location.KeyMode)
	assert.Equal(t, "root", www.Location.KeyOwner)
	assert.Equal(t, []string{providers.WarnKeyModeOpen, providers.WarnKeyGroupOpen}, www.Location.Warnings)
	require.Len(t, www.Location.Servers, 1)
	assert.Equal(t, []string{"www.example.test"}, www.Location.Servers[0].Names)
	assert.Equal(t, rnSites, www.Location.Servers[0].File)
	assert.Equal(t, []string{"|443"}, listens(www))
	assert.False(t, www.Location.Symlinked)
	assert.False(t, www.Location.CustomLocation)

	api := supported(rnAPI)
	assert.Equal(t, "0640", api.Location.KeyMode)
	assert.Empty(t, api.Location.Warnings, "root:root 0640 is not open")
	supported(rnSharedA)
	supported(rnSharedB)
	assert.Equal(t, rnSharedKey, locs[rnSharedB].Location.KeyPath, "two certificates, one key file")
	dualRSA, dualEC := supported(rnDualRSA), supported(rnDualEC)
	assert.Equal(t, dualRSA.Location.Servers, dualEC.Location.Servers, "one server block, two locations")

	sc := supported(h.scCert())
	assert.Equal(t, "0640", sc.Location.KeyMode)
	assert.Equal(t, h.scGroup, sc.Location.KeyGroup)
	assert.Equal(t, []string{providers.WarnKeyGroupOpen}, sc.Location.Warnings, "a key its group can read (Debian's ssl-cert)")

	le := supported(rnLE)
	assert.True(t, le.Location.Symlinked)
	assert.Equal(t, rnLEArchive+"/fullchain1.pem", le.Location.ResolvedCertPath)
	assert.Contains(t, le.Location.Warnings, providers.WarnSymlinked)

	assert.Equal(t, []string{h.ip + "|4443"}, listens(supported(rnIP)))
	assert.ElementsMatch(t, []string{"127.0.0.1|8443", "::1|8443"}, listens(supported(rnLoop)))
	assert.Equal(t, []string{rnLoopbackName + "|8445"}, listens(supported(rnLH)))
	assert.Equal(t, []string{h.hostname + "|9443"}, listens(supported(rnHN)))
	ns := supported(rnNS)
	assert.Positive(t, ns.Location.FreeBytes)
	assert.LessOrEqual(t, ns.Location.FreeBytes, int64(256<<10), "the 256 KiB tmpfs")
	// The helper drops the block Go cannot parse (OpenSSL's negative serial number) and says so at
	// server level; the location keeps the leaf.
	dropped := supported(rnDropped)
	assert.Equal(t, 1, chainLength(dropped.PEMChain))
	assert.Equal(t, 2, chainLength([]byte(h.sh("cat "+rnDropped))), "nginx loads both blocks")

	var variable bool
	for _, c := range res.Certificates {
		if c.Location.Unsupported == providers.UnsupportedVariable {
			variable = strings.Contains(c.Location.CertPath, "$ssl_server_name")
			assert.Empty(t, c.PEMChain)
		}
	}
	assert.True(t, variable, "the certificate path with a variable is listed as unsupported")
	unsupported(rnEnc, providers.UnsupportedPasswordFile)
	unsupported(rnCombo, providers.UnsupportedCombinedFile)
	// A key file a user owns (in a root-controlled directory) is supported with key_group_open (S10:
	// the owner is kept); a key reached through a link a user owns is not.
	user := supported(rnUser)
	assert.Equal(t, "deploy", user.Location.KeyOwner)
	assert.Equal(t, []string{providers.WarnKeyGroupOpen}, user.Location.Warnings)
	link := unsupported(rnLink, providers.UnsupportedFile)
	assert.Equal(t, providers.CertProblemNotRootControlled, link.Location.KeyProblem, "a link a user owns: %+v", link.Location)
	hl := unsupported(rnHL, providers.UnsupportedFile)
	assert.Equal(t, providers.CertProblemHardLinked, hl.Location.KeyProblem)
	ud := unsupported(rnUD, providers.UnsupportedFile)
	assert.Equal(t, providers.CertProblemNotRootControlled, ud.Location.Problem)
	assert.Empty(t, ud.PEMChain, "nothing is read from a user's directory")
	unsupported(rnWR, providers.UnsupportedConfigFileWritable)
	unsupported(rnStream, providers.UnsupportedStream)
	_, mailListed := locs[rnMail]
	assert.False(t, mailListed, "TLS in mail {} is never a location: only the mail_tls warning")
	codes := warningCodes(res.Warnings)
	assert.Contains(t, codes, providers.WarnStreamTLS)
	assert.Contains(t, codes, providers.WarnMailTLS)
	assert.Contains(t, codes, providers.WarnCertificateBlockDropped)
	writable := warningsOf(res.Warnings, providers.WarnConfigFileWritable)
	require.Len(t, writable, 1)
	assert.Equal(t, rnWRConf, writable[0].Params["path"])
	assert.NotContains(t, codes, "nginx_config_invalid")
}

